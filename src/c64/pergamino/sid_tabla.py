"""sid_tabla.inc for sid.s: the tone periods the parchments' music writes, sorted, and the SID frequency of each,
1064250 / P (integer division, as sid.s's fallback division; at most $FFFF).

    sid_tabla.py [OUT]      (default: sid_tabla.inc next to this script)

The periods: the 12 notes of the CPC player's table (the words at 6197h of the first stage, the same in the ending)
in 8 octaves (>> 0-7), and every other period the two tunes write (the ending's singing line: its vibrato, a period
up and down; data/pruebas/salida_musica_{inicial,final}/cpc_ticks.txt, the CPC's own writes, which musica.c and
musica.s reproduce tick by tick).  With them sid.s finds every period of both tunes by its binary search and never
divides (a division is ~1350 cycles; the ending's line wrote one every 4 ticks)."""
import os, sys

AQUI = os.path.dirname(os.path.realpath(__file__))
P = AQUI
while not os.path.isdir(os.path.join(P, "..", "data")):
    P = os.path.dirname(P)
sys.path.insert(0, os.path.join(P, "..", "tools"))
from licencia import cabecera   # noqa: E402  (the GPL header of the generated sources)


def main():
    salida = sys.argv[1] if len(sys.argv) > 1 else os.path.join(AQUI, "sid_tabla.inc")
    m = open(os.path.join(P, "..", "data", "cpc64", "cinta", "primera_etapa.bin"), "rb").read()
    notas = [m[0x6197 + 2 * i] | m[0x6198 + 2 * i] << 8 for i in range(12)]
    periodos = {w >> o for w in notas for o in range(8)}
    n_notas = len(periodos)
    for tono in ("inicial", "final"):
        regs = [0] * 16
        for linea in open(os.path.join(P, "..", "data", "pruebas", f"salida_musica_{tono}", "cpc_ticks.txt")):
            t, r, v = map(int, linea.split())
            regs[r] = v
            if r in (1, 3, 5):
                c = r // 2
                periodos.add(regs[2 * c] | (regs[2 * c + 1] & 0x0F) << 8)
    periodos.discard(0)                                  # (sid.s: period 0 is the highest, not looked up)
    p = sorted(periodos)
    assert len(p) <= 255
    f = [min(1064250 // x, 0xFFFF) for x in p]
    lista = lambda v: ", ".join(f"${x:02X}" for x in v)
    with open(salida, "w") as o:
        o.write(cabecera("asm"))
        o.write("; generated by sid_tabla.py: the tone periods of the parchments' music, sorted (the 12 notes in 8 octaves,\n"
                f"; 6197h >> octave: {n_notas}; the ending's vibrato: {len(p) - n_notas} more), and the SID frequency of each,\n"
                "; 1064250 / P (integer division, as the fallback division)\n")
        o.write(f"NPERIODOS = {len(p)}\n")
        o.write(f"tab_p_lo: .byte {lista([x & 255 for x in p])}\n")
        o.write(f"tab_p_hi: .byte {lista([x >> 8 for x in p])}\n")
        o.write(f"tab_f_lo: .byte {lista([x & 255 for x in f])}\n")
        o.write(f"tab_f_hi: .byte {lista([x >> 8 for x in f])}\n")
    print(f"{salida}: {len(p)} periods ({n_notas} notes)")


if __name__ == "__main__":
    main()
