"""Stubs for the functions the 6502 code calls but nobody has translated yet: stubs64.s, stubs64.tsv.

    stubs64.py [DIR]

Every name a 6502 source (*.s but stubs64.s) imports with `.import` and no source exports becomes a stub:
the byte 02h (JAM: it never runs on a real 6502) and the function's Z80 entry, found by name in the C
translation's tables (juego/f_*.c, funciones.c: { 0xXXXX, "name", ...}).  The hybrid host's 6502 core stops
at a 02h and runs the Z80 original on the CPC form of the memory (juego/m6502/sombra6502.c, "traps"), so a
routine can be checked before its callees are translated.  The C64's own build must have no stub (the
script fails then with --final).  stubs64.tsv: name, Z80 entry (the host reads it).
"""
import glob, os, re, sys

S = os.path.dirname(os.path.abspath(__file__))            # the sources (the .s files)
D = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith("-") else S)  # the generated files
J = os.path.join(os.path.dirname(os.path.dirname(S)), "juego")
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(S)), "..", "tools"))
from licencia import cabecera   # noqa: E402  (the GPL header of the generated sources)
importa, exporta = set(), set()
# (plataforma/c128.s: the C128's own routines, imported by the game only with -D C128; what it imports, the other
# platform files export)
PLAT = os.path.join(os.path.dirname(S), "plataforma")
for f in glob.glob(os.path.join(S, "*.s")) + [os.path.join(PLAT, "c128.s")] + glob.glob(os.path.join(PLAT, "*.s")):
    if os.path.basename(f) == "stubs64.s": continue
    plataforma = os.path.dirname(f) == PLAT and os.path.basename(f) != "c128.s"
    for l in open(f):
        l = l.split(";")[0]
        m = re.match(r"\s*\.(import|export)\s+(.*)", l)
        if m:
            nombres = [n.strip().split(":")[0].split("=")[0].strip() for n in m.group(2).split(",")]
            if m.group(1) == "import" and not plataforma: importa.update(n for n in nombres if n)
            elif m.group(1) == "export": exporta.update(n for n in nombres if n)
entradas = {}
for f in glob.glob(os.path.join(J, "f_*.c")) + [os.path.join(J, "funciones.c")]:
    for m in re.finditer(r'\{\s*0x([0-9A-Fa-f]{4})u?\s*,\s*"([^"]+)"', open(f).read()):
        entradas.setdefault(m.group(2), int(m.group(1), 16))
faltan = sorted(importa - exporta)
sin = [n for n in faltan if n not in entradas]
if sin:
    sys.exit("stubs64.py: imported, not exported and not a translated function: " + " ".join(sin))
if faltan and "--final" in sys.argv:
    sys.exit("stubs64.py: stubs in the final build: " + " ".join(faltan))
with open(os.path.join(D, "stubs64.s"), "w") as s:
    s.write(cabecera("asm"))
    s.write("; generated by stubs64.py: functions not translated yet (02h + the Z80 entry: a trap in the host)\n")
    if faltan: s.write("        .export " + ", ".join(faltan) + "\n")
    s.write('.segment "CODE"\n')
    for n in faltan:
        s.write(f"{n}:\n        .byte $02\n        .word ${entradas[n]:04X}\n")
with open(os.path.join(D, "stubs64.tsv"), "w") as t:
    t.write("# name, Z80 entry: the stubs of stubs64.s (generated by stubs64.py)\n")
    for n in faltan: t.write(f"{n}\t{entradas[n]:04X}\n")
print(f"{len(faltan)} stubs")
