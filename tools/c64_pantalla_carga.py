"""SUPERSEDED by doc/revisiones/pantalla_carga/pantalla.py, which decodes the CPC's memory itself; the PENS.bin this tool
read (data/cpc64/pantalla_carga/pens.bin, from cpc_carga.py) was decoded with the mode 0 pen bits 1 and 2
swapped (fixed in cpc_carga.py since), so its colours were wrong.
The loading screen of the CPC 64 KiB version as a C64 multicolour bitmap.

    c64_pantalla_carga.py PENS.bin INKS.txt OUT.c [PNG]

PENS.bin: 128 x 192 CPC mode 0 pens (cpc64/pantalla_carga, from the screen once the first stage has
shown it: 32 x 24 characters); INKS.txt: the 16 inks as the stage gives them to SCR SET INK
(firmware colour numbers, & 1Fh).  A mode 0 pixel is a C64 multicolour pixel, so the picture is
copied 1:1, centred (16 pixels from the left, 4 lines from the top).  Each CPC colour becomes the
nearest C64 colour (CIE Lab, palette pepto); each 4x8 cell keeps black ($D021) plus its 3 most used
colours, any other colour taking the nearest of those.
"""
import math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from c64_colores import lab, vpl

FW2HW = [0x54, 0x44, 0x55, 0x5C, 0x58, 0x5D, 0x4C, 0x45, 0x4D, 0x56, 0x46, 0x57, 0x5E, 0x40, 0x5F, 0x4E, 0x47,
         0x4F, 0x52, 0x42, 0x53, 0x5A, 0x59, 0x5B, 0x4A, 0x43, 0x4B]
HW = [(128,128,128),(128,128,128),(0,255,128),(255,255,128),(0,0,128),(255,0,128),(0,128,128),(255,128,128),
      (255,0,128),(255,255,128),(255,255,0),(255,255,255),(255,0,0),(255,0,255),(255,128,0),(255,128,255),
      (0,0,128),(0,255,128),(0,255,0),(0,255,255),(0,0,0),(0,0,255),(0,128,0),(0,128,255),
      (128,0,128),(128,255,128),(128,255,0),(128,255,255),(128,0,0),(128,0,255),(128,128,0),(128,128,255)]


def main():
    pens = open(sys.argv[1], "rb").read()
    inks = [int(x, 16) for x in open(sys.argv[2]).read().split()]
    pal = vpl("/usr/share/vice/C64/pepto-pal.vpl")
    rgb = [HW[FW2HW[(v & 0x1F) % 27] & 0x1F] for v in inks]
    c64 = [min(range(16), key=lambda i: math.dist(lab(c), lab(pal[i]))) for c in rgb]
    W, H = 128, 192
    img = [[0] * 160 for _ in range(200)]
    for y in range(H):
        for x in range(W):
            img[y + 4][x + 16] = c64[pens[y * W + x]]
    bitmap = bytearray(8000); screen = bytearray(1000); color = bytearray(1000)
    for cy in range(25):
        for cx in range(40):
            cols = [img[cy * 8 + l][cx * 4 + k] for l in range(8) for k in range(4)]
            count = {}
            for c in cols:
                if c: count[c] = count.get(c, 0) + 1
            keep = sorted(count, key=lambda c: -count[c])[:3]
            while len(keep) < 3: keep.append(0)
            bits = {0: 0, keep[0]: 1, keep[1]: 2, keep[2]: 3}
            for l in range(8):
                v = 0
                for k in range(4):
                    c = img[cy * 8 + l][cx * 4 + k]
                    if c not in bits:
                        c = min([0] + keep, key=lambda d: math.dist(lab(pal[c]), lab(pal[d])))
                    v = (v << 2) | bits[c]
                bitmap[(cy * 40 + cx) * 8 + l] = v
            screen[cy * 40 + cx] = (keep[0] << 4) | keep[1]
            color[cy * 40 + cx] = keep[2]
    def arr(name, data):
        rows = ",\n".join("  " + ",".join(f"0x{b:02X}" for b in data[i:i + 20]) for i in range(0, len(data), 20))
        return f"const unsigned char {name}[{len(data)}] = {{\n{rows}\n}};\n"
    with open(sys.argv[3], "w") as f:
        f.write("/* generated by tools/c64_pantalla_carga.py: the CPC 64 KiB version's loading screen */\n")
        f.write(arr("carga_bitmap", bitmap) + arr("carga_pantalla", screen) + arr("carga_color", color))
    print("CPC inks -> C64:", c64)
    if len(sys.argv) > 4:                                   # preview with the pepto palette
        import struct, zlib
        rows = []
        for y in range(200):
            line = bytearray()
            for cx in range(40):
                s, c3 = screen[(y >> 3) * 40 + cx], color[(y >> 3) * 40 + cx]
                cc = [0, s >> 4, s & 15, c3]
                b = bitmap[((y >> 3) * 40 + cx) * 8 + (y & 7)]
                for k in range(4):
                    line += bytes(pal[cc[(b >> (6 - 2 * k)) & 3]]) * 2
            rows.append(b"\0" + bytes(line))
        def chunk(t, d): return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
        open(sys.argv[4], "wb").write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 320, 200, 8, 2, 0, 0, 0))
                                      + chunk(b"IDAT", zlib.compress(b"".join(rows), 9)) + chunk(b"IEND", b""))


if __name__ == "__main__":
    main()
