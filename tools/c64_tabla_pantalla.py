"""The table that turns a CPC mode 1 byte (4 pixels) into a C64 multicolour half byte (2 pixels).

    c64_tabla_pantalla.py OUT.inc

Pixel pairs: the right pixel of each pair (the CPC graphics put the black outline on the left of most
mixed pairs), except a byte whose pixels alternate a b a b (the fluting of the columns), which keeps
a then b so the stripes stay.  CPC pen -> multicolour bit pair: 3 -> 00 ($D021, black), 0 -> 01,
1 -> 10, 2 -> 11 (the CPC's inks are the C64's four colours of every cell).  The half byte is given
in the low 4 bits (right half of a bitmap byte); the left half is the same shifted 4.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from licencia import cabecera   # noqa: E402  (the GPL header of the generated sources)
BITS = {3: 0, 0: 1, 1: 2, 2: 3}


def pens(b):
    return [((b >> (7 - i)) & 1) | (((b >> (3 - i)) & 1) << 1) for i in range(4)]


def nibble(b):
    p = pens(b)
    if p[0] == p[2] and p[1] == p[3] and p[0] != p[1]:
        a, c = p[0], p[1]                      # a b a b: keep the stripes
    else:
        a, c = p[1], p[3]                      # the right pixel of each pair
    return BITS[a] << 2 | BITS[c]


def main():
    with open(sys.argv[1], "w") as f:
        f.write(cabecera("asm"))
        f.write("; generated by tools/c64_tabla_pantalla.py: CPC mode 1 byte -> C64 multicolour half byte\n")
        for i in range(0, 256, 16):
            f.write("        .byte " + ", ".join(f"${nibble(b):02X}" for b in range(i, i + 16)) + "\n")


if __name__ == "__main__":
    main()
