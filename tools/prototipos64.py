"""src/juego/juego64.h: the prototype of every game function the groups' files define (not static), so
any file can call any translated function in C.

    prototipos64.py [JUEGO_DIR]

Scans src/juego/f_*.c and funciones.c for function definitions at the start of a line; the wrappers (w_*)
and checks (r_*) are static and left out.  Each prototype carries the 64K address of the comment that
precedes the definition ("/* XXXX name ...").  Types the prototypes need (iso_vm) come from the data
headers included at the top.
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from licencia import cabecera   # noqa: E402  (the GPL header of the generated sources)

J = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "juego"))
DEF = re.compile(r'^((?:const\s+)?[A-Za-z_][\w]*(?:\s*\*+)?)\s+\**\s*(\w+)\s*\(([^;{)]*)\)\s*\n\{', re.M)
fuentes = sorted(f for f in os.listdir(J) if f.startswith("f_") and f.endswith(".c")) + ["funciones.c"]
salida = ["/* juego64.h: the prototypes of the game's C functions, generated by tools/prototipos64.py",
          " * from src/juego/f_*.c and funciones.c (do not edit; run the tool again after adding functions). */",
          "#ifndef JUEGO64_H", "#define JUEGO64_H", '#include "juego.h"', '#include "datos_motor_iso.h"   /* iso_vm */', ""]
vistos = {}
for f in fuentes:
    s = open(os.path.join(J, f)).read()
    filas = []
    for m in DEF.finditer(s):
        ret, nombre, args = m.group(1).strip(), m.group(2), " ".join(m.group(3).split())
        linea_ini = s.rfind("\n", 0, m.start())
        if s[m.start():m.start() + 7] == "static ": continue
        if nombre in ("main",) or ret in ("static", "else", "return"): continue
        if "z80" in args: continue                  # the hybrid host's result checks (juego.h declares them)
        prev = s[:m.start()].rstrip()
        dir64 = ""
        if prev.endswith("*/"):
            c = prev[prev.rfind("/*"):]
            mm = re.match(r"/\*\s*([0-9A-F]{4})\b", c)
            if mm: dir64 = mm.group(1)
        if nombre in vistos:
            print(f"duplicate: {nombre} in {f} and {vistos[nombre]}", file=sys.stderr); continue
        vistos[nombre] = f
        filas.append(f"{ret} {nombre}({args or 'void'});" + (f"   /* {dir64} */" if dir64 else ""))
    if filas:
        salida.append(f"/* {f} */")
        salida += filas
        salida.append("")
salida.append("#endif")
open(os.path.join(J, "juego64.h"), "w").write(cabecera("c") + "\n".join(salida) + "\n")
print(f"{len(vistos)} prototypes")
